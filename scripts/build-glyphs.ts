// Builds src/vision/glyph-templates.ts from labelled Madden 27 screenshots in scripts/fixtures.
// Labels list every glyph segment() finds in each region, left to right ('_' = ignore).
// Arrows: '<' '>' = possession arrow, 'v' '^' = ball-spot arrow (own / opponent territory).
import { readFileSync, writeFileSync } from 'node:fs';
import { PNG } from 'pngjs';
import { grayFromRGBA, regionMask, resizeGray } from '../src/vision/gray.ts';
import { REGIONS, THRESHOLD } from '../src/vision/regions.ts';
import { segment } from '../src/vision/glyphs.ts';

type R = keyof typeof THRESHOLD;
const LABELS: Record<string, Partial<Record<R, string>>> = {
  'defense-2nd-inches.png': {
    downDistance: '<2ND&INCHES', quarter: '1ST', clock: '5:06', ballSpot: 'v45_', leftScore: '0', rightScore: '0',
  },
  'offense-2nd-10.png': {
    downDistance: '2ND&10>', quarter: '1ST', clock: '0:48', ballSpot: 'v30_', leftScore: '6', rightScore: '7',
  },
  'offense-3rd-17.png': {
    downDistance: '3RD&17>', quarter: '2ND', clock: '1:56', ballSpot: '^25_', leftScore: '13', rightScore: '7',
  },
};

const SIZES = [[1920, 1080], [2560, 1440], [1280, 720]] as const;
const lib: Record<string, string[]> = {};
for (const [file, regions] of Object.entries(LABELS)) {
  const png = PNG.sync.read(readFileSync(new URL(`./fixtures/${file}`, import.meta.url)));
  const base = grayFromRGBA(png.data, png.width, png.height);
  // Train on the native frame plus common monitor sizes so other resolutions still read.
  for (const [w, h] of SIZES) {
   const img = resizeGray(base, w, h);
   for (const [r, labels] of Object.entries(regions) as [R, string][]) {
    const glyphs = segment(regionMask(img, REGIONS[r], THRESHOLD[r]));
    if (glyphs.length !== labels.length) { console.warn(`skip ${file} ${r} @${w}: found ${glyphs.length} glyphs, labels "${labels}"`); continue; }
    glyphs.forEach((g, i) => {
      const ch = labels[i];
      if (ch === '_') return;
      lib[ch] ??= [];
      if (!lib[ch].includes(g.bits)) lib[ch].push(g.bits);
    });
   }
  }
}

const hex = (bits: string) => bits.match(/.{1,4}/g)!.map((n) => parseInt(n.padEnd(4, '0'), 2).toString(16)).join('');
const body = Object.keys(lib).sort().map((k) => `  ${JSON.stringify(k)}: [\n${lib[k].map((b) => `    '${hex(b)}',`).join('\n')}\n  ],`).join('\n');
writeFileSync(new URL('../src/vision/glyph-templates.ts', import.meta.url),
  `// Generated by scripts/build-glyphs.ts from real Madden 27 screenshots — do not edit by hand.\n` +
  `// Each entry is a glyph bitmap (row by row), packed as hex: 4 pixels per character.\n` +
  `const TEMPLATES: Record<string, string[]> = {\n${body}\n};\nexport default TEMPLATES;\n`);
console.log('characters:', Object.keys(lib).sort().join(' '), '| templates:', Object.values(lib).reduce((a, b) => a + b.length, 0));
